// 不带声调的拼音映射
const toneMap: Record<string, string> = {
  "ā": "a", "á": "a", "ǎ": "a", "à": "a",
  "ē": "e", "é": "e", "ě": "e", "è": "e",
  "ī": "i", "í": "i", "ǐ": "i", "ì": "i",
  "ō": "o", "ó": "o", "ǒ": "o", "ò": "o",
  "ū": "u", "ú": "u", "ǔ": "u", "ù": "u",
  "ǖ": "v", "ǘ": "v", "ǚ": "v", "ǜ": "v",
  "ü": "v",
};

/**
 * 获取汉字拼音
 * @param char 汉字
 * @param withTone 是否带声调
 * @returns 拼音，未知字符返回原字符
 */
export function getPinyin(char: string, withTone: boolean = true): string {
  const pinyin = pinyinMap[char];
  if (!pinyin) return char;

  if (withTone) return pinyin;

  // 去除声调
  return pinyin.split("").map(c => toneMap[c] || c).join("");
}

/**
 * 文本转拼音
 * @param text 输入文本
 * @param withTone 是否带声调
 * @param firstLetterOnly 是否只取首字母
 * @param separator 分隔符
 * @returns 拼音字符串
 */
export function textToPinyin(
  text: string,
  withTone: boolean = true,
  firstLetterOnly: boolean = false,
  separator: string = " "
): string {
  if (!text) return "";

  const result: string[] = [];
  let lastIsChinese = false;

  for (const char of text) {
    // 检查是否是汉字
    if (/[\u4e00-\u9fa5]/.test(char)) {
      let py = getPinyin(char, withTone);
      if (firstLetterOnly) {
        py = py.charAt(0);
      }
      result.push(py);
      lastIsChinese = true;
    } else if (/\s/.test(char)) {
      // 空白字符作为分隔
      if (lastIsChinese) {
        // 已经有拼音分隔了，跳过
      }
      lastIsChinese = false;
    } else {
      // 非汉字字符，直接追加
      result.push(char);
      lastIsChinese = false;
    }
  }

  // 使用分隔符连接拼音
  // 更智能的连接：汉字之间用分隔符，非汉字字符直接拼接
  let output = "";
  let prevIsChinese = false;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const isChinese = /[\u4e00-\u9fa5]/.test(char);

    if (isChinese) {
      let py = getPinyin(char, withTone);
      if (firstLetterOnly) {
        py = py.charAt(0);
      }
      if (prevIsChinese && output) {
        output += separator;
      }
      output += py;
      prevIsChinese = true;
    } else {
      output += char;
      prevIsChinese = false;
    }
  }

  return output;
}

/**
 * 获取拼音库字数
 */
export function getPinyinCount(): number {
  return Object.keys(pinyinMap).length;
}
