const simpToTradMap: Record<string, string> = {};
for (const [simp, trad] of simpTradPairs) {
  simpToTradMap[simp] = trad;
}

// 构建繁体转简体映射
const tradToSimpMap: Record<string, string> = {};
for (const [simp, trad] of simpTradPairs) {
  tradToSimpMap[trad] = simp;
}

// 简体转繁体
export function simplifiedToTraditional(text: string): string {
  let result = "";
  for (const char of text) {
    result += simpToTradMap[char] || char;
  }
  return result;
}

// 繁体转简体
export function traditionalToSimplified(text: string): string {
  let result = "";
  for (const char of text) {
    result += tradToSimpMap[char] || char;
  }
  return result;
}

// 获取覆盖字数
export function getCharCount(): number {
  return simpTradPairs.length;
}
